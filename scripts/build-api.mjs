// Bundles each server entry into ONE self-contained file under api/ai/ (JSON inlined, no imports to resolve),
// which is what Vercel deploys as a Node function. Sources live in server/ and src/ai; api/ai/*.js is generated
// and committed so a deploy never depends on TypeScript/ESM resolution quirks. CI fails if it drifts (npm run api:check).
import { build } from 'esbuild';

const entries = { ask: 'server/entry/ask.ts', status: 'server/entry/status.ts', usage: 'server/entry/usage.ts' };

await build({
  entryPoints: Object.fromEntries(Object.entries(entries).map(([name, file]) => [`api/ai/${name}`, file])),
  outdir: '.',
  outExtension: { '.js': '.js' },
  bundle: true,
  platform: 'node',
  target: 'node20',
  format: 'esm',
  minify: false,
  legalComments: 'none',
  banner: { js: '// GENERATED by scripts/build-api.mjs from server/ — do not edit. Run `npm run api:build`.' },
  logLevel: 'warning',
});
console.log('built', Object.keys(entries).map(n => `api/ai/${n}.js`).join(', '));
