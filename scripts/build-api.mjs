// Bundles each server entry into ONE self-contained file under api/ai/ (JSON inlined, no imports to resolve),
// which is what Vercel deploys as a Node function. Sources live in server/ and src/ai; api/ai/*.js is generated
// and committed so a deploy never depends on TypeScript/ESM resolution quirks. CI fails if it drifts (npm run api:check).
import { build } from 'esbuild';

const entries = {
  'ai/ask': 'server/entry/ask.ts', 'ai/status': 'server/entry/status.ts', 'ai/usage': 'server/entry/usage.ts',
  'facts/dig': 'server/entry/facts-dig.ts', 'facts/report': 'server/entry/facts-report.ts', 'facts/admin': 'server/entry/facts-admin.ts',
  'me': 'server/entry/me.ts', 'unfurl': 'server/entry/unfurl.ts', 'leaderboard': 'server/entry/leaderboard.ts',
};

await build({
  entryPoints: Object.fromEntries(Object.entries(entries).map(([name, file]) => [`api/${name}`, file])),
  outdir: '.',
  outExtension: { '.js': '.js' },
  bundle: true,
  platform: 'node',
  target: 'node20',
  format: 'esm',
  minify: false,
  legalComments: 'none',
  banner: { js: '// GENERATED by scripts/build-api.mjs from server/ — do not edit. Run `npm run api:build`.' },
  logLevel: 'warning',
});
console.log('built', Object.keys(entries).map(n => `api/${n}.js`).join(', '));
