/**
 * Writes data/facts/SPOT_CHECK.md: 20 computed facts sampled with a fixed stride, each shown with the raw inputs it was
 * derived from so a human can verify the arithmetic and judge plausibility. (A unit test re-derives the same families
 * with independent code on every run.)   npx tsx scripts/facts/spot-check.ts
 */
import fs from 'node:fs';
import path from 'node:path';
import facts from '../../src/data/generated/facts.computed.json';
import { rulers } from '../../src/data/rulers';
import { realms, getDynasty } from '../../src/data/registry';
import type { Fact } from '../../src/facts/model';

const all = facts as unknown as Fact[];
const family = (f: Fact) => f.id.replace(/^c_/, '').replace(/_[0-9a-f]{10}$/, '');
const pick = (fam: string, n: number) => { const l = all.filter(f => family(f) === fam); const step = Math.max(1, Math.floor(l.length / n)); return Array.from({ length: n }, (_, i) => l[i * step]).filter(Boolean); };
const sample = [...pick('reign', 6), ...pick('concurrent', 5), ...pick('overlap', 4), ...pick('reach', 3), ...pick('region_peak', 2)].slice(0, 20);

const lines = [
  '# Spot check of computed facts', '',
  `Generated by \`scripts/facts/spot-check.ts\` (deterministic stride sample of ${sample.length} of ${all.length} facts). For each fact: the claim, then the raw records it came from.`,
  'The arithmetic is also re-derived by independent code in `src/facts/facts.test.ts` ("SPOT CHECK") on every test run.', '',
  '**Reviewer notes (owner):** tick each box after reading the raw inputs; strike any fact that reads wrongly.', '',
];
sample.forEach((f, i) => {
  lines.push(`## ${i + 1}. ${family(f)} — \`${f.id}\``, '', `- [ ] **${f.claim.en}**`, `- Persian: ${f.claim.fa}`, `- Status: ${f.status}`);
  if (family(f) === 'reign') {
    const r = Object.values(rulers).find(x => x.name.en === f.entityName.en)!;
    lines.push(`- Raw: rulers.ts → ${r.name.en}: startDate ${r.startDate}, endDate ${r.endDate} (⇒ ${r.endDate - r.startDate} years)`);
  } else if (family(f) === 'concurrent') {
    const y = f.year!; const ids = [...new Set(realms.filter(r => y >= r.start && y <= r.end).map(r => r.dynastyId))];
    lines.push(`- Raw: ${ids.length} distinct dynasties have a realm record covering ${y}:`, `  ${ids.map(id => getDynasty(id)!.name.en).sort().join('; ')}`);
  } else if (family(f) === 'overlap') {
    const m = f.derivedFrom ? f.sources[0].match(/\((.+?), (.+?) in "(.+?)"\)/) : null;
    if (m) for (const id of [m[1], m[2]]) lines.push(`- Raw: ${id} in ${m[3]}: ${realms.filter(r => r.dynastyId === id && r.regionId === m[3]).map(r => `${r.start}…${r.end}`).join(', ')}`);
  } else if (family(f) === 'reach' || family(f) === 'region_peak') {
    lines.push(`- Source: ${f.sources[0]}; derived from the registry realm rows (see docs/historical_data via src/data/generated/realms.json)`);
  }
  lines.push('');
});
fs.writeFileSync(path.resolve(import.meta.dirname, '../../data/facts/SPOT_CHECK.md'), lines.join('\n'));
console.log(`wrote data/facts/SPOT_CHECK.md (${sample.length} facts)`);
